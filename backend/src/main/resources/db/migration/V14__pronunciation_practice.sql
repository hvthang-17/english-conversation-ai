CREATE TABLE pronunciation_drills (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    lesson_id BIGINT NOT NULL,
    reference_text TEXT NOT NULL,
    locale VARCHAR(16) NOT NULL,
    mode VARCHAR(20) NOT NULL,
    status VARCHAR(16) NOT NULL,
    sort_order INT NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    INDEX ix_pronunciation_drill_lesson (lesson_id, status, sort_order, id),
    CONSTRAINT fk_pronunciation_drill_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(id),
    CONSTRAINT ck_pronunciation_drill_mode CHECK (mode IN ('READ_ALOUD','SHADOWING')),
    CONSTRAINT ck_pronunciation_drill_status CHECK (status IN ('DRAFT','ACTIVE','ARCHIVED')),
    CONSTRAINT ck_pronunciation_reference CHECK (CHAR_LENGTH(TRIM(reference_text)) BETWEEN 1 AND 1000),
    CONSTRAINT ck_pronunciation_drill_locale CHECK (locale = 'en-US')
);

CREATE TABLE pronunciation_attempts (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    drill_id BIGINT NOT NULL,
    ai_request_id BIGINT NOT NULL,
    client_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    mode VARCHAR(16) NOT NULL DEFAULT 'SCRIPTED',
    drill_mode VARCHAR(20) NOT NULL,
    status VARCHAR(24) NOT NULL,
    error_code VARCHAR(80) NULL,
    reference_text_snapshot TEXT NOT NULL,
    recognized_text TEXT NULL,
    overall_score DECIMAL(5,2) NULL,
    accuracy DECIMAL(5,2) NULL,
    fluency DECIMAL(5,2) NULL,
    completeness DECIMAL(5,2) NULL,
    prosody DECIMAL(5,2) NULL,
    detail_json JSON NULL,
    provider VARCHAR(32) NOT NULL,
    locale VARCHAR(16) NOT NULL,
    assessment_version VARCHAR(64) NOT NULL,
    audio_storage_key VARCHAR(512) NULL,
    audio_expires_at DATETIME(6) NULL,
    audio_deleted_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    scored_at DATETIME(6) NULL,
    UNIQUE KEY uq_pronunciation_client_request (user_id, client_request_id),
    UNIQUE KEY uq_pronunciation_ai_request (ai_request_id),
    UNIQUE KEY uq_pronunciation_audio_key (audio_storage_key),
    INDEX ix_pronunciation_history (user_id, id),
    INDEX ix_pronunciation_audio_expiry (audio_expires_at),
    CONSTRAINT fk_pronunciation_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_pronunciation_drill FOREIGN KEY (drill_id) REFERENCES pronunciation_drills(id),
    CONSTRAINT fk_pronunciation_request FOREIGN KEY (ai_request_id) REFERENCES ai_requests(id) ON DELETE CASCADE,
    CONSTRAINT ck_pronunciation_mode CHECK (mode = 'SCRIPTED' AND drill_mode IN ('READ_ALOUD','SHADOWING')),
    CONSTRAINT ck_pronunciation_status CHECK (status IN (
        'PENDING','RUNNING','SUCCEEDED','FAILED','UNKNOWN','INSUFFICIENT_EVIDENCE')),
    CONSTRAINT ck_pronunciation_scores CHECK (
        overall_score BETWEEN 0 AND 100 AND accuracy BETWEEN 0 AND 100
        AND fluency BETWEEN 0 AND 100 AND completeness BETWEEN 0 AND 100 AND prosody IS NULL)
);
